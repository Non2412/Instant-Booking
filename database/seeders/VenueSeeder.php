    /**
     * Create interactive tables, courts, or rooms for each venue.
     */
    protected function createItemsForVenue(Venue $venue, string $groupKey): void
    {
        $items = [];

        switch ($groupKey) {
            case 'restaurant':
                for ($i = 1; $i <= 12; $i++) {
                    $cap = ($i % 5 === 0) ? 8 : (($i % 3 === 0) ? 6 : (($i % 2 === 0) ? 2 : 4));
                    $items[] = [
                        'item_code' => "T{$i}",
                        'name' => "โต๊ะ {$i}",
                        'capacity_label' => "{$cap} ที่นั่ง",
                        'capacity' => $cap,
                        'shape' => ($i % 3 === 0) ? 'round' : 'square',
                        'sort_order' => $i,
                        'is_active' => true,
                    ];
                }
                break;

            case 'cafe':
                for ($i = 1; $i <= 10; $i++) {
                    $cap = ($i % 4 === 0) ? 6 : (($i % 2 === 0) ? 2 : 4);
                    $items[] = [
                        'item_code' => "C{$i}",
                        'name' => "โต๊ะกาแฟ {$i}",
                        'capacity_label' => "{$cap} ที่นั่ง",
                        'capacity' => $cap,
                        'shape' => ($i % 2 === 0) ? 'round' : 'square',
                        'sort_order' => $i,
                        'is_active' => true,
                    ];
                }
                break;

            case 'football':
                $count = 5;
                for ($i = 1; $i <= $count; $i++) {
                    $cap = ($i % 2 === 0) ? 14 : 10;
                    $sizeLabel = ($i % 2 === 0) ? '7 คน' : '5 คน';
                    $items[] = [
                        'item_code' => "สนาม {$i}",
                        'name' => "สนามฟุตบอล {$i} ({$sizeLabel})",
                        'capacity_label' => '1 ชม.',
                        'capacity' => $cap,
                        'shape' => 'square',
                        'sort_order' => $i,
                        'is_active' => true,
                    ];
                }
                break;

            case 'badminton':
                $count = 8;
                for ($i = 1; $i <= $count; $i++) {
                    $items[] = [
                        'item_code' => "คอร์ท {$i}",
                        'name' => "คอร์ทแบดมินตัน {$i}",
                        'capacity_label' => '1 ชม.',
                        'capacity' => 4,
                        'shape' => 'square',
                        'sort_order' => $i,
                        'is_active' => true,
                    ];
                }
                break;

            case 'sports':
                $count = 6;
                for ($i = 1; $i <= $count; $i++) {
                    $items[] = [
                        'item_code' => "คอร์ท {$i}",
                        'name' => "คอร์ท / ลู่ {$i}",
                        'capacity_label' => '1 ชม.',
                        'capacity' => 4,
                        'shape' => 'square',
                        'sort_order' => $i,
                        'is_active' => true,
                    ];
                }
                break;

            case 'meeting_room':
                $roomNames = ['Room A (เล็ก)', 'Room B (กลาง)', 'Room C (ใหญ่)', 'Room D (บอร์ดรูม)', 'Room E (เวิร์กช็อป)', 'Room F (สัมมนา)'];
                $caps = [4, 8, 12, 16, 20, 30];
                foreach ($roomNames as $idx => $rName) {
                    $cap = $caps[$idx] ?? 8;
                    $items[] = [
                        'item_code' => 'ห้อง '.chr(65 + $idx),
                        'name' => $rName,
                        'capacity_label' => "{$cap} ที่นั่ง",
                        'capacity' => $cap,
                        'shape' => 'square',
                        'sort_order' => $idx + 1,
                        'is_active' => true,
                    ];
                }
                break;
        }

        foreach ($items as $itemData) {
            $venue->items()->create($itemData);
        }
    }
